# Checks every Flatpak ID in image/apps/apps.json against Flathub's API and writes the result to
# image/apps/verified-flatpak-ids.txt (one line per app: id, licence, latest version).
# Needs network (curl, jq). Run it whenever apps.json changes; CI runs it on every pull request.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
manifest=$here/../apps/apps.json
out=${1:-$here/../apps/verified-flatpak-ids.txt}
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
failed=0
{
  echo "# Generated by image/tests/verify-flathub.sh on $(date -u +%Y-%m-%d) from the Flathub API."
  echo "# id | licence | latest version"
} >"$tmp"
while read -r id; do
  if ! json=$(curl -fsS --retry 3 "https://flathub.org/api/v2/appstream/$id"); then
    echo "::error::Flatpak $id is not on Flathub (apps.json)" >&2
    failed=1
    continue
  fi
  printf '%s | %s | %s\n' "$id" "$(jq -r '.project_license // "?"' <<<"$json")" \
    "$(jq -r '.releases[0].version // "?"' <<<"$json")" >>"$tmp"
  echo "ok  $id"
done < <(jq -r '.apps[] | select(.kind == "flatpak") | .flatpak.id' "$manifest")
((failed == 0)) || exit 1
mv "$tmp" "$out"
trap - EXIT
