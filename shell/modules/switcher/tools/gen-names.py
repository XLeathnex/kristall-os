"""gen-names.py MANIFEST OUT — writes the switcher's names.js from the app manifest
(docs/contracts/apps.md): our display names by desktop id and by the product names apps put into
their window titles. The switcher runs inside KWin, which cannot read the manifest itself.
The generated file is committed; the switcher's static test checks that it is up to date."""
import json
import sys

doc = json.load(open(sys.argv[1], encoding="utf-8"))
by_desktop, by_product = {}, {}
for a in doc["apps"]:
    names = {"en": a["name"]["en"], "de": a["name"]["de"]}
    by_desktop[a["desktop_id"][:-len(".desktop")].lower()] = names
    for p in a.get("product_names", []):
        by_product[p] = names
out = ("// SPDX-License-Identifier: GPL-3.0-or-later\n"
       "// Generated by tools/gen-names.py from image/apps/apps.json — do not edit.\n"
       ".pragma library\n\n"
       "var byDesktop = " + json.dumps(by_desktop, ensure_ascii=False, sort_keys=True) + ";\n\n"
       "var byProduct = " + json.dumps(by_product, ensure_ascii=False, sort_keys=True) + ";\n")
with open(sys.argv[2], "w", encoding="utf-8") as f:
    f.write(out)
