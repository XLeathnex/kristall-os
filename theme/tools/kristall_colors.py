"""Kristall colour derivation shared by the build-time generators and the appearance service.

Everything is derived from tokens.json (design.md values). Standard library only, so the
appearance service can import it on the owner's machine without extra packages.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TOKEN_PATHS = [
    os.environ.get("KRISTALL_THEME_TOKENS", ""),
    os.path.join(HERE, "..", "tokens", "tokens.json"),        # repository
    "/usr/share/kristall/theme/tokens.json",                   # installed
]


def load_tokens():
    for p in TOKEN_PATHS:
        if p and os.path.exists(p):
            with open(p, encoding="utf-8") as f:
                return json.load(f)
    raise FileNotFoundError("tokens.json not found")


def hex2rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb2hex(c):
    return "#%02X%02X%02X" % tuple(max(0, min(255, int(round(v)))) for v in c[:3])


def over(fg, alpha, bg):
    """composite colour fg at alpha over opaque bg"""
    f, b = hex2rgb(fg), hex2rgb(bg)
    return rgb2hex([f[i] * alpha + b[i] * (1 - alpha) for i in range(3)])


def mix(a, b, t):
    return over(b, t, a)


def kde(h):
    return "%d,%d,%d" % hex2rgb(h)


def luminance(h):
    def lin(c):
        c /= 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (lin(v) for v in hex2rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def accent_hex(tokens, accent, mode):
    a = tokens["accents"].get(accent) or tokens["accents"]["blue"]
    return a[mode]


def palette(tokens, mode, accent="blue"):
    """Opaque role colours for one appearance (mode 'light'|'dark')."""
    s = tokens["schemes"][mode]
    ink = s["ink"]
    acc = accent_hex(tokens, accent, mode)
    p = {
        "accent": acc,
        "accentText": "#FFFFFF",
        "label": s["label"],
        "window": s["window"],
        "view": s["view"],
        "viewAlternate": s["viewAlternate"],
        "header": s["window"],
        "headerInactive": s["headerInactive"],
        "button": s["button"],
        "tooltip": s["tooltip"],
        "secondary": over(ink, s["secondaryAlpha"], s["window"]),
        "secondaryOnView": over(ink, s["secondaryAlpha"], s["view"]),
        "tertiary": over(ink, s["tertiaryAlpha"], s["window"]),
        "separator": over(ink, s["separatorAlpha"], s["window"]),
        "separatorOnView": over(ink, s["separatorAlpha"], s["view"]),
        "border": over(ink, s["borderAlpha"], s["window"]),
        "hover": over(acc, 0.35, s["view"]),
        "destructive": s["destructive"],
        "success": s["success"],
        "warning": s["warning"],
        "warningText": s["warningText"],
        "link": acc,
        "visited": mix(acc, "#AF52DE" if mode == "light" else "#BF5AF2", 0.5),
        "focus": acc,
        "complementaryBg": tokens["complementary"]["background"],
        "complementaryLabel": tokens["complementary"]["label"],
    }
    # yellow and graphite accents carry dark text in macOS (white on yellow is unreadable)
    if accent == "yellow":
        p["accentText"] = "#1D1D1F"
    return p


def _set(lines, group, entries):
    lines.append(f"[{group}]")
    for k, v in entries:
        lines.append(f"{k}={v}")
    lines.append("")


def colorscheme(tokens, mode, accent="blue"):
    """A KDE colour scheme (.colors) for the given appearance."""
    p = palette(tokens, mode, accent)
    dark = mode == "dark"
    name_en = "Kristall Dark" if dark else "Kristall Light"
    name_de = "Kristall Dunkel" if dark else "Kristall Hell"
    neg_bg = mix(p["view"], p["destructive"], 0.18)
    neu_bg = mix(p["view"], p["warning"], 0.22)
    pos_bg = mix(p["view"], p["success"], 0.18)

    def colors(bg, alt, fg, inactive):
        return [
            ("BackgroundAlternate", kde(alt)),
            ("BackgroundNormal", kde(bg)),
            ("DecorationFocus", kde(p["focus"])),
            ("DecorationHover", kde(p["accent"])),
            ("ForegroundActive", kde(p["accent"])),
            ("ForegroundInactive", kde(inactive)),
            ("ForegroundLink", kde(p["link"])),
            ("ForegroundNegative", kde(p["destructive"])),
            ("ForegroundNeutral", kde(p["warningText"])),
            ("ForegroundNormal", kde(fg)),
            ("ForegroundPositive", kde(mix(p["success"], "#000000", 0.25) if not dark else p["success"])),
            ("ForegroundVisited", kde(p["visited"])),
        ]

    L = [
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        f"# Kristall OS colour scheme ({mode}), generated by theme/tools/gen-theme.py from theme/tokens/tokens.json.",
        "# The accent colours in it are replaced at runtime by plasma-apply-colorscheme --accent-color.",
        "",
    ]
    _set(L, "ColorEffects:Disabled", [("Color", "56,56,56"), ("ColorAmount", "0"), ("ColorEffect", "0"),
                                       ("ContrastAmount", "0.65"), ("ContrastEffect", "1"),
                                       ("IntensityAmount", "0.1"), ("IntensityEffect", "2")])
    _set(L, "ColorEffects:Inactive", [("ChangeSelectionColor", "true"), ("Color", "112,111,110"), ("ColorAmount", "0.025"),
                                       ("ColorEffect", "2"), ("ContrastAmount", "0.1"), ("ContrastEffect", "2"),
                                       ("Enable", "false"), ("IntensityAmount", "0"), ("IntensityEffect", "0")])
    _set(L, "Colors:Button", colors(p["button"], mix(p["button"], p["accent"], 0.15), p["label"], p["secondary"]))
    _set(L, "Colors:Complementary", colors(p["complementaryBg"], "#2A2A2C", p["complementaryLabel"],
                                           over("#FFFFFF", 0.55, p["complementaryBg"])))
    _set(L, "Colors:Header", colors(p["header"], p["header"], p["label"], p["secondary"]))
    _set(L, "Colors:Header][Inactive", colors(p["headerInactive"], p["headerInactive"], p["secondary"], p["tertiary"]))
    sel = colors(p["accent"], mix(p["accent"], "#FFFFFF" if not dark else "#000000", 0.2), p["accentText"], p["accentText"])
    sel = [(k, v) if k not in ("ForegroundActive", "ForegroundLink", "ForegroundVisited") else (k, kde(p["accentText"])) for k, v in sel]
    _set(L, "Colors:Selection", sel)
    _set(L, "Colors:Tooltip", colors(p["tooltip"], p["tooltip"], p["label"], p["secondary"]))
    _set(L, "Colors:View", colors(p["view"], p["viewAlternate"], p["label"], p["secondaryOnView"]))
    _set(L, "Colors:Window", colors(p["window"], p["viewAlternate"] if not dark else "#2C2C2E", p["label"], p["secondary"]))
    _set(L, "General", [("ColorScheme", "KristallDark" if dark else "KristallLight"), ("Name", name_en),
                        ("Name[de]", name_de), ("shadeSortColumn", "false")])
    _set(L, "KDE", [("contrast", "4")])
    _set(L, "WM", [("activeBackground", kde(p["header"])), ("activeBlend", kde(p["header"])),
                   ("activeForeground", kde(p["label"])), ("inactiveBackground", kde(p["headerInactive"])),
                   ("inactiveBlend", kde(p["headerInactive"])), ("inactiveForeground", kde(p["secondary"]))])
    # keep the derived background tints for positive/neutral/negative rows in sync with Breeze's use
    _ = (neg_bg, neu_bg, pos_bg)
    return "\n".join(L)


def konsole_scheme(tokens, mode, accent="blue"):
    t = tokens["terminal"][mode]
    acc = accent_hex(tokens, accent, mode)
    name = "Kristall Dark" if mode == "dark" else "Kristall Light"
    L = ["# SPDX-License-Identifier: GPL-3.0-or-later",
         "# Kristall terminal colours, generated from theme/tokens/tokens.json", ""]
    _set(L, "Background", [("Color", kde(t["bg"]))])
    _set(L, "BackgroundIntense", [("Color", kde(t["bg"]))])
    _set(L, "BackgroundFaint", [("Color", kde(t["bg"]))])
    for i in range(8):
        _set(L, f"Color{i}", [("Color", kde(t["normal"][i]))])
        _set(L, f"Color{i}Intense", [("Color", kde(t["bright"][i]))])
        _set(L, f"Color{i}Faint", [("Color", kde(mix(t["normal"][i], t["bg"], 0.35)))])
    _set(L, "Foreground", [("Color", kde(t["fg"]))])
    _set(L, "ForegroundIntense", [("Color", kde(t["fg"]))])
    _set(L, "ForegroundFaint", [("Color", kde(mix(t["fg"], t["bg"], 0.35)))])
    _set(L, "General", [("Anchor", "0.5,0.5"), ("Blur", "false"), ("ColorRandomization", "false"),
                        ("Description", name), ("FillStyle", "Tile"), ("Opacity", "1"), ("Wallpaper", ""),
                        ("WallpaperFlipType", "NoFlip"), ("WallpaperOpacity", "1")])
    _ = acc
    return "\n".join(L)



